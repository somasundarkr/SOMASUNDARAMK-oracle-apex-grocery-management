--------------------------------------------------------------------------------
-- SECTION 3 : STOCK PACKAGE
-- All stock changes go through ADJUST_STOCK, so the "never below zero" rule
-- lives in exactly one place.
--------------------------------------------------------------------------------
CREATE OR REPLACE PACKAGE grocery_stock_pkg AS

    -- Returns current stock of a product (0 if not found)
    FUNCTION get_stock (p_product_id IN NUMBER) RETURN NUMBER;

    -- Adds p_change to stock (use a negative number to reduce stock).
    -- Raises ORA-20001 if stock would become negative.
    PROCEDURE adjust_stock (p_product_id IN NUMBER, p_change IN NUMBER);

END grocery_stock_pkg;
/

CREATE OR REPLACE PACKAGE BODY grocery_stock_pkg AS

    FUNCTION get_stock (p_product_id IN NUMBER) RETURN NUMBER IS
        l_qty grocery_product.qty_in_stock%TYPE;
    BEGIN
        SELECT qty_in_stock
          INTO l_qty
          FROM grocery_product
         WHERE product_id = p_product_id;
        RETURN l_qty;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RETURN 0;
    END get_stock;


    PROCEDURE adjust_stock (p_product_id IN NUMBER, p_change IN NUMBER) IS
        l_qty   grocery_product.qty_in_stock%TYPE;
        l_name  grocery_product.product_name%TYPE;
    BEGIN
        -- Lock the product row so two users cannot sell the same stock at once
        SELECT qty_in_stock, product_name
          INTO l_qty, l_name
          FROM grocery_product
         WHERE product_id = p_product_id
           FOR UPDATE;

        IF l_qty + p_change < 0 THEN
            RAISE_APPLICATION_ERROR(-20001,
                'Not enough stock for ' || l_name ||
                '. Available: ' || l_qty ||
                ', required: '  || ABS(p_change) || '.');
        END IF;

        UPDATE grocery_product
           SET qty_in_stock = qty_in_stock + p_change
         WHERE product_id = p_product_id;
    END adjust_stock;

END grocery_stock_pkg;
/


--------------------------------------------------------------------------------
-- SECTION 4 : TRIGGERS
-- These fire for EVERY insert/update/delete - from APEX forms, interactive
-- grids, SQL Workshop or scripts - so stock is always correct.
--   * Price is copied from the product if not entered
--   * TOTAL_AMOUNT = QUANTITY x PRICE
--   * Purchase  -> stock goes UP
--   * Sale      -> stock goes DOWN (blocked if insufficient)
--   * Editing or deleting a record reverses its old effect first
--------------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER grocery_purchase_biud
BEFORE INSERT OR UPDATE OR DELETE ON grocery_purchase
FOR EACH ROW
BEGIN
    IF INSERTING OR UPDATING THEN
        IF :NEW.purchase_price IS NULL THEN
            SELECT purchase_price
              INTO :NEW.purchase_price
              FROM grocery_product
             WHERE product_id = :NEW.product_id;
        END IF;
        :NEW.total_amount := :NEW.quantity * :NEW.purchase_price;
    END IF;

    IF UPDATING AND :OLD.product_id = :NEW.product_id THEN
        -- same product, only quantity changed: apply the difference
        grocery_stock_pkg.adjust_stock(:NEW.product_id, :NEW.quantity - :OLD.quantity);
    ELSE
        IF UPDATING OR DELETING THEN
            grocery_stock_pkg.adjust_stock(:OLD.product_id, -:OLD.quantity);  -- undo old purchase
        END IF;
        IF INSERTING OR UPDATING THEN
            grocery_stock_pkg.adjust_stock(:NEW.product_id,  :NEW.quantity);  -- add new purchase
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER grocery_sale_biud
BEFORE INSERT OR UPDATE OR DELETE ON grocery_sale
FOR EACH ROW
BEGIN
    IF INSERTING OR UPDATING THEN
        IF :NEW.selling_price IS NULL THEN
            SELECT selling_price
              INTO :NEW.selling_price
              FROM grocery_product
             WHERE product_id = :NEW.product_id;
        END IF;
        :NEW.total_amount := :NEW.quantity * :NEW.selling_price;
    END IF;

    IF UPDATING AND :OLD.product_id = :NEW.product_id THEN
        grocery_stock_pkg.adjust_stock(:NEW.product_id, :OLD.quantity - :NEW.quantity);
    ELSE
        IF UPDATING OR DELETING THEN
            grocery_stock_pkg.adjust_stock(:OLD.product_id,  :OLD.quantity);  -- return old sale to stock
        END IF;
        IF INSERTING OR UPDATING THEN
            grocery_stock_pkg.adjust_stock(:NEW.product_id, -:NEW.quantity);  -- take new sale from stock
        END IF;
    END IF;
END;
/


--------------------------------------------------------------------------------
-- SECTION 5 : REPORT VIEWS
-- Views join the IDs to readable names so APEX reports stay simple.
--------------------------------------------------------------------------------
CREATE OR REPLACE VIEW grocery_product_v AS
SELECT p.product_id,
       p.product_name,
       c.category_name,
       s.supplier_name,
       p.unit,
       p.purchase_price,
       p.selling_price,
       p.qty_in_stock,
       p.reorder_level,
       p.qty_in_stock * p.purchase_price             AS stock_value,
       p.expiry_date,
       p.status,
       CASE
           WHEN p.qty_in_stock = 0                THEN 'OUT OF STOCK'
           WHEN p.qty_in_stock <= p.reorder_level THEN 'LOW STOCK'
           ELSE 'OK'
       END                                           AS stock_status,
       p.category_id,
       p.supplier_id
  FROM grocery_product  p
  JOIN grocery_category c ON c.category_id = p.category_id
  JOIN grocery_supplier s ON s.supplier_id = p.supplier_id;

CREATE OR REPLACE VIEW grocery_purchase_v AS
SELECT pu.purchase_id,
       pu.purchase_date,
       s.supplier_name,
       p.product_name,
       p.unit,
       pu.quantity,
       pu.purchase_price,
       pu.total_amount,
       pu.supplier_id,
       pu.product_id
  FROM grocery_purchase pu
  JOIN grocery_supplier s ON s.supplier_id = pu.supplier_id
  JOIN grocery_product  p ON p.product_id  = pu.product_id;

CREATE OR REPLACE VIEW grocery_sale_v AS
SELECT sa.sale_id,
       sa.sale_date,
       c.customer_name,
       p.product_name,
       p.unit,
       sa.quantity,
       sa.selling_price,
       sa.total_amount,
       sa.quantity * (sa.selling_price - p.purchase_price) AS profit,
       sa.customer_id,
       sa.product_id
  FROM grocery_sale     sa
  JOIN grocery_customer c ON c.customer_id = sa.customer_id
  JOIN grocery_product  p ON p.product_id  = sa.product_id;

CREATE OR REPLACE VIEW grocery_daily_sales_v AS
SELECT TRUNC(sa.sale_date)                                 AS sale_day,
       COUNT(*)                                            AS no_of_sales,
       COUNT(DISTINCT sa.customer_id)                      AS no_of_customers,
       SUM(sa.quantity)                                    AS items_sold,
       SUM(sa.total_amount)                                AS total_sales,
       SUM(sa.quantity * (sa.selling_price - p.purchase_price)) AS total_profit
  FROM grocery_sale    sa
  JOIN grocery_product p ON p.product_id = sa.product_id
 GROUP BY TRUNC(sa.sale_date);


