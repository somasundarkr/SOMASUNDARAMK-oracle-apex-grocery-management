-- SECTION 1 : TABLES
-- "GENERATED BY DEFAULT ON NULL AS IDENTITY" creates the primary key value
-- automatically (Oracle manages a hidden sequence for you). APEX forms work
-- with it out of the box.
--------------------------------------------------------------------------------

-- 1.1 Categories -------------------------------------------------------------
CREATE TABLE grocery_category (
    category_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    category_name   VARCHAR2(100)  NOT NULL,
    description     VARCHAR2(400),
    CONSTRAINT grocery_category_pk      PRIMARY KEY (category_id),
    CONSTRAINT grocery_category_name_uk UNIQUE (category_name)
);

-- 1.2 Suppliers --------------------------------------------------------------
CREATE TABLE grocery_supplier (
    supplier_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    supplier_name   VARCHAR2(150)  NOT NULL,
    phone           VARCHAR2(15)   NOT NULL,
    email           VARCHAR2(150),
    address         VARCHAR2(400),
    CONSTRAINT grocery_supplier_pk       PRIMARY KEY (supplier_id),
    CONSTRAINT grocery_supplier_name_uk  UNIQUE (supplier_name),
    CONSTRAINT grocery_supplier_phone_ck CHECK (REGEXP_LIKE(phone, '^[0-9+ -]{7,15}$')),
    CONSTRAINT grocery_supplier_email_ck CHECK (email IS NULL OR REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

-- 1.3 Customers --------------------------------------------------------------
CREATE TABLE grocery_customer (
    customer_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    customer_name   VARCHAR2(150)  NOT NULL,
    phone           VARCHAR2(15)   NOT NULL,
    email           VARCHAR2(150),
    address         VARCHAR2(400),
    CONSTRAINT grocery_customer_pk       PRIMARY KEY (customer_id),
    CONSTRAINT grocery_customer_phone_ck CHECK (REGEXP_LIKE(phone, '^[0-9+ -]{7,15}$')),
    CONSTRAINT grocery_customer_email_ck CHECK (email IS NULL OR REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$'))
);

-- 1.4 Products ---------------------------------------------------------------
CREATE TABLE grocery_product (
    product_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    product_name    VARCHAR2(150)  NOT NULL,
    category_id     NUMBER         NOT NULL,
    supplier_id     NUMBER         NOT NULL,
    unit            VARCHAR2(20)   NOT NULL,
    purchase_price  NUMBER(10,2)   NOT NULL,
    selling_price   NUMBER(10,2)   NOT NULL,
    qty_in_stock    NUMBER(10)     DEFAULT ON NULL 0        NOT NULL,
    reorder_level   NUMBER(10)     DEFAULT ON NULL 10       NOT NULL,
    expiry_date     DATE,
    status          VARCHAR2(10)   DEFAULT ON NULL 'ACTIVE' NOT NULL,
    CONSTRAINT grocery_product_pk         PRIMARY KEY (product_id),
    CONSTRAINT grocery_product_name_uk    UNIQUE (product_name),
    CONSTRAINT grocery_product_cat_fk     FOREIGN KEY (category_id)
                                          REFERENCES grocery_category (category_id),
    CONSTRAINT grocery_product_sup_fk     FOREIGN KEY (supplier_id)
                                          REFERENCES grocery_supplier (supplier_id),
    CONSTRAINT grocery_product_unit_ck    CHECK (unit IN ('KG','GRAM','LITRE','ML','PACK','PIECE','BOTTLE','DOZEN')),
    CONSTRAINT grocery_product_pprice_ck  CHECK (purchase_price > 0),
    -- Business rule: selling price >= purchase price
    CONSTRAINT grocery_product_price_ck   CHECK (selling_price >= purchase_price),
    -- Business rule: quantity cannot be negative
    CONSTRAINT grocery_product_qty_ck     CHECK (qty_in_stock >= 0),
    CONSTRAINT grocery_product_reorder_ck CHECK (reorder_level >= 0),
    CONSTRAINT grocery_product_status_ck  CHECK (status IN ('ACTIVE','INACTIVE'))
);

-- 1.5 Purchases (stock coming IN from suppliers) -----------------------------
CREATE TABLE grocery_purchase (
    purchase_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    purchase_date   DATE           DEFAULT ON NULL SYSDATE NOT NULL,
    supplier_id     NUMBER         NOT NULL,
    product_id      NUMBER         NOT NULL,
    quantity        NUMBER(10)     NOT NULL,
    purchase_price  NUMBER(10,2)   NOT NULL,   -- defaults from product if left empty
    total_amount    NUMBER(12,2)   NOT NULL,   -- always calculated by trigger
    CONSTRAINT grocery_purchase_pk          PRIMARY KEY (purchase_id),
    CONSTRAINT grocery_purchase_sup_fk      FOREIGN KEY (supplier_id)
                                            REFERENCES grocery_supplier (supplier_id),
    CONSTRAINT grocery_purchase_product_fk  FOREIGN KEY (product_id)
                                            REFERENCES grocery_product (product_id),
    CONSTRAINT grocery_purchase_qty_ck      CHECK (quantity > 0),
    CONSTRAINT grocery_purchase_price_ck    CHECK (purchase_price > 0)
);

-- 1.6 Sales (stock going OUT to customers) -----------------------------------
CREATE TABLE grocery_sale (
    sale_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    sale_date       DATE           DEFAULT ON NULL SYSDATE NOT NULL,
    customer_id     NUMBER         NOT NULL,
    product_id      NUMBER         NOT NULL,
    quantity        NUMBER(10)     NOT NULL,
    selling_price   NUMBER(10,2)   NOT NULL,   -- defaults from product if left empty
    total_amount    NUMBER(12,2)   NOT NULL,   -- always calculated by trigger
    CONSTRAINT grocery_sale_pk          PRIMARY KEY (sale_id),
    CONSTRAINT grocery_sale_cust_fk     FOREIGN KEY (customer_id)
                                        REFERENCES grocery_customer (customer_id),
    CONSTRAINT grocery_sale_product_fk  FOREIGN KEY (product_id)
                                        REFERENCES grocery_product (product_id),
    CONSTRAINT grocery_sale_qty_ck      CHECK (quantity > 0),
    CONSTRAINT grocery_sale_price_ck    CHECK (selling_price > 0)
);


